// Stock replenishment pipeline (item 1): when a raw material's onHand drops
// below its lowThreshold, auto-create a draft PurchaseOrder (or send a low-stock
// alert) so procurement can act. Best-effort, never blocks the caller.
import prisma from '../lib/prisma.js';
import { audit } from '../lib/audit.js';

// Reorder quantity: bring stock up to 2x the threshold.
async function reorderQty(mat) {
  const threshold = Number(mat.lowThreshold) || 5;
  const target = threshold * 2;
  const needed = Math.max(1, Math.ceil(target - Number(mat.onHand || 0)));
  return needed;
}

// Find low-stock materials and create draft POs for them (grouped by supplier).
export async function replenishLowStock(userId = null) {
  const materials = await prisma.rawMaterial.findMany({ take: 500 });
  const lowMaterials = materials.filter((m) => Number(m.onHand) <= Number(m.lowThreshold));

  if (!lowMaterials.length) return [];

  const groups = new Map();
  for (const m of lowMaterials) {
    const supplierName = m.supplier || m.suggestedSupplier || 'Auto-replenish (unassigned)';
    if (!groups.has(supplierName)) groups.set(supplierName, []);
    groups.get(supplierName).push(m);
  }

  const created = [];
  for (const [supplierName, mats] of groups) {
    const existingDraft = await prisma.purchaseOrder.findFirst({
      where: { supplier: supplierName, status: 'draft' },
      include: { lines: true },
    });
    if (existingDraft) {
      const existingMatIds = new Set(existingDraft.lines.map((l) => l.rawMaterialId));
      const newLines = [];
      for (const m of mats) {
        if (existingMatIds.has(m.id)) continue;
        const qty = await reorderQty(m);
        newLines.push({ rawMaterialId: m.id, qty, unitCost: Number(m.costPerUnit) || null });
      }
      if (newLines.length) {
        await prisma.purchaseOrderLine.createMany({
          data: newLines.map((l) => ({ purchaseOrderId: existingDraft.id, ...l })),
        });
        created.push(existingDraft);
      }
      continue;
    }

    const supplierId = await (async () => {
      const s = await prisma.supplier.findFirst({ where: { name: { equals: supplierName, mode: 'insensitive' } }, select: { id: true } });
      return s ? s.id : null;
    })();

    const poNumber = 'PO-DRAFT-' + Date.now().toString().slice(-6);
    const lines = [];
    for (const m of mats) {
      const qty = await reorderQty(m);
      lines.push({ rawMaterialId: m.id, qty, unitCost: Number(m.costPerUnit) || null });
    }
    const po = await prisma.purchaseOrder.create({
      data: {
        poNumber,
        supplier: supplierName,
        supplierId,
        notes: 'Auto-generated by stock replenishment pipeline',
        createdBy: userId,
        status: 'draft',
        lines: { create: lines },
      },
      include: { lines: true },
    });
    created.push(po);
    await audit({ actorId: userId, action: 'replenishment.draft_po', entityType: 'purchase_order', entityId: po.id, details: { materials: mats.length, supplier: supplierName } }).catch(() => {});
  }
  return created;
}

export async function checkAndReplenish(materialId, userId = null) {
  const mat = await prisma.rawMaterial.findUnique({ where: { id: materialId } });
  if (!mat || Number(mat.onHand) > Number(mat.lowThreshold)) return null;
  return replenishLowStock(userId);
}
