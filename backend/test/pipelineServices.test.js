import { test, before, after } from 'node:test';
import assert from 'node:assert/strict';
import prisma from '../src/lib/prisma.js';
import { startServer, api } from './helpers.js';
import { replenishLowStock, checkAndReplenish } from '../src/services/replenishment.js';
import { recalculateRecipeCosts } from '../src/services/costRecalc.js';
import { suggestSubstitutes } from '../src/services/bomPricing.js';

let srv;
let adminToken;
const auth = () => ({ Authorization: `Bearer ${adminToken}` });
const UNIQUE = Date.now().toString(36);

before(async () => {
  srv = await startServer();
  const login = await api(srv.base, '/api/auth/login', {
    method: 'POST', body: JSON.stringify({ email: 'admin@krystal.local', password: 'admin123' }),
  });
  assert.equal(login.status, 200);
  adminToken = login.body.token;
});

after(async () => {
  await prisma.rawMaterial.deleteMany({ where: { sku: { startsWith: `PI-${UNIQUE}` } } }).catch(() => {});
  await prisma.purchaseOrder.deleteMany({ where: { notes: 'Auto-generated by stock replenishment pipeline' } }).catch(() => {});
  await srv.close();
});

// ── replenishment ──────────────────────────────────────────────────────
test('replenishLowStock creates draft PO for low-stock material', async () => {
  const mat = await prisma.rawMaterial.create({
    data: { sku: `PI-${UNIQUE}-LOW`, name: 'Low Stock Material', unit: 'sheet', costPerUnit: 1.5, onHand: 2, lowThreshold: 10, supplier: 'Test Supplier' },
  });
  const pos = await replenishLowStock(null);
  assert.ok(Array.isArray(pos));
  const draftPo = pos.find((p) => p.supplier === 'Test Supplier');
  assert.ok(draftPo, 'should create a draft PO');
  assert.equal(draftPo.status, 'draft');
  assert.ok(draftPo.lines.length >= 1);
  await prisma.rawMaterial.delete({ where: { id: mat.id } }).catch(() => {});
  await prisma.purchaseOrder.delete({ where: { id: draftPo.id } }).catch(() => {});
});

test('replenishLowStock returns empty when no low-stock materials', async () => {
  // Ensure no materials are below threshold
  await prisma.rawMaterial.updateMany({ where: { onHand: { lte: 0 } }, data: { onHand: 100 } });
  const pos = await replenishLowStock(null);
  assert.ok(Array.isArray(pos));
});

test('checkAndReplenish skips when material is above threshold', async () => {
  const mat = await prisma.rawMaterial.create({
    data: { sku: `PI-${UNIQUE}-HIGH`, name: 'High Stock Material', unit: 'sheet', costPerUnit: 1, onHand: 50, lowThreshold: 5 },
  });
  const result = await checkAndReplenish(mat.id, null);
  assert.equal(result, null);
  await prisma.rawMaterial.delete({ where: { id: mat.id } }).catch(() => {});
});

test('checkAndReplenish triggers when material is below threshold', async () => {
  const mat = await prisma.rawMaterial.create({
    data: { sku: `PI-${UNIQUE}-TRIG`, name: 'Trigger Material', unit: 'sheet', costPerUnit: 1, onHand: 1, lowThreshold: 10, supplier: 'Trig Supplier' },
  });
  const result = await checkAndReplenish(mat.id, null);
  assert.ok(result === null || Array.isArray(result));
  await prisma.rawMaterial.delete({ where: { id: mat.id } }).catch(() => {});
  await prisma.purchaseOrder.deleteMany({ where: { supplier: 'Trig Supplier', status: 'draft' } }).catch(() => {});
});

// ── costRecalc ──────────────────────────────────────────────────────────
test('recalculateRecipeCosts returns empty for unused material', async () => {
  const mat = await prisma.rawMaterial.create({
    data: { sku: `PI-${UNIQUE}-UNUSED`, name: 'Unused Material', unit: 'sheet', costPerUnit: 1, onHand: 10, lowThreshold: 5 },
  });
  const result = await recalculateRecipeCosts(mat.id, null);
  assert.deepEqual(result, []);
  await prisma.rawMaterial.delete({ where: { id: mat.id } }).catch(() => {});
});

test('recalculateRecipeCosts recomputes for linked recipe', async () => {
  // Create material, recipe, and line
  const mat = await prisma.rawMaterial.create({
    data: { sku: `PI-${UNIQUE}-COST`, name: 'Cost Test Material', unit: 'sheet', costPerUnit: 2, onHand: 10, lowThreshold: 5 },
  });
  const recipe = await prisma.bOMRecipe.create({
    data: { labourMinutesPerUnit: 10, cricutMinutesPerUnit: 5 },
  });
  await prisma.bOMLine.create({
    data: { recipeId: recipe.id, rawMaterialId: mat.id, qtyPerUnit: 3, wasteFactor: 0.05 },
  });
  const result = await recalculateRecipeCosts(mat.id, null);
  assert.equal(result.length, 1);
  assert.equal(result[0].recipeId, recipe.id);
  assert.ok(typeof result[0].materialsCost === 'number');
  assert.ok(typeof result[0].retail === 'number');
  // Cleanup
  await prisma.bOMLine.deleteMany({ where: { recipeId: recipe.id } }).catch(() => {});
  await prisma.bOMRecipe.delete({ where: { id: recipe.id } }).catch(() => {});
  await prisma.rawMaterial.delete({ where: { id: mat.id } }).catch(() => {});
});

// ── suggestSubstitutes ──────────────────────────────────────────────────
test('suggestSubstitutes returns empty for no candidates', async () => {
  const mat = await prisma.rawMaterial.create({
    data: { sku: `PI-${UNIQUE}-SUB1`, name: 'Unique Material XYZ', unit: 'sheet', costPerUnit: 1, onHand: 10, lowThreshold: 5, colour: 'Purple', weightValue: 999, weightUnit: 'gsm' },
  });
  const subs = await suggestSubstitutes(prisma, mat, 5);
  assert.ok(Array.isArray(subs));
  await prisma.rawMaterial.delete({ where: { id: mat.id } }).catch(() => {});
});

test('suggestSubstitutes finds matching candidates', async () => {
  const mat = await prisma.rawMaterial.create({
    data: { sku: `PI-${UNIQUE}-SUB2`, name: 'Cardstock Blush', unit: 'sheet', costPerUnit: 1, onHand: 0, lowThreshold: 5, colour: 'Blush', weightValue: 65, weightUnit: 'lb' },
  });
  const candidate = await prisma.rawMaterial.create({
    data: { sku: `PI-${UNIQUE}-SUB3`, name: 'Cardstock Blush Alt', unit: 'sheet', costPerUnit: 1.2, onHand: 50, lowThreshold: 5, colour: 'Blush', weightValue: 65, weightUnit: 'lb' },
  });
  const subs = await suggestSubstitutes(prisma, mat, 5);
  assert.ok(subs.length >= 1);
  assert.ok(subs.some((s) => s.id === candidate.id));
  await prisma.rawMaterial.delete({ where: { id: mat.id } }).catch(() => {});
  await prisma.rawMaterial.delete({ where: { id: candidate.id } }).catch(() => {});
});

