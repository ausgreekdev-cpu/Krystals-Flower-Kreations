test('material PATCH with cost change triggers recalc', async () => {
  const mat = await prisma.rawMaterial.create({
    data: { sku: `PI-${UNIQUE}-RECALC`, name: 'Recalc Material', unit: 'sheet', costPerUnit: 1, onHand: 10, lowThreshold: 5 },
  });
  const recipe = await prisma.bOMRecipe.create({ data: { labourMinutesPerUnit: 10, cricutMinutesPerUnit: 5 } });
  await prisma.bOMLine.create({ data: { recipeId: recipe.id, rawMaterialId: mat.id, qtyPerUnit: 2, wasteFactor: 0.05 } });

  // Update cost — should trigger recalc (fire-and-forget, just verify no error)
  const res = await api(srv.base, `/api/bom/materials/${mat.id}`, {
    method: 'PATCH', headers: auth(),
    body: JSON.stringify({ costPerUnit: 3.5 }),
  });
  assert.equal(res.status, 200);

  // Cleanup
  await prisma.bOMLine.deleteMany({ where: { recipeId: recipe.id } }).catch(() => {});
  await prisma.bOMRecipe.delete({ where: { id: recipe.id } }).catch(() => {});
  await prisma.rawMaterial.delete({ where: { id: mat.id } }).catch(() => {});
});
