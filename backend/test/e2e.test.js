test('E2E: replenish endpoint creates draft POs', async () => {
  // Create a low-stock material
  const mat = await prisma.rawMaterial.create({
    data: { sku: `E2E-${UNIQUE}-LOW`, name: 'E2E Low Material', unit: 'sheet', costPerUnit: 1, onHand: 1, lowThreshold: 10, supplier: 'E2E Supplier' },
  });
  const res = await api(srv.base, '/api/procurement/replenish', { method: 'POST', headers: auth() });
  assert.equal(res.status, 200);
  assert.ok(typeof res.body.created === 'number');
  // Cleanup
  await prisma.rawMaterial.delete({ where: { id: mat.id } }).catch(() => {});
  await prisma.purchaseOrder.deleteMany({ where: { supplier: 'E2E Supplier', status: 'draft' } }).catch(() => {});
});

