// End-to-end smoke test: exercises the full pipeline from procedure import
// through checkout, stock consumption, replenishment, and QC.
import { test, before, after } from 'node:test';
import assert from 'node:assert/strict';
import prisma from '../src/lib/prisma.js';
import { startServer, api } from './helpers.js';
import { analyzeWithRules } from '../src/services/procedureAnalyzer.js';

let srv;
let adminToken;
const auth = () => ({ Authorization: `Bearer ${adminToken}` });
const UNIQUE = Date.now().toString(36);

const PROCEDURE = `# E2E Test Flower ${UNIQUE}
SKU: E2E-${UNIQUE}

## Materials
- 3 sheets 65lb cardstock blush
- 1 meter floral tape

## Steps
1. Cut petals
2. Assemble bloom

Time: 20 minutes
`;

before(async () => {
  srv = await startServer();
  const login = await api(srv.base, '/api/auth/login', {
    method: 'POST', body: JSON.stringify({ email: 'admin@krystal.local', password: 'admin123' }),
  });
  assert.equal(login.status, 200);
  adminToken = login.body.token;
});

after(async () => {
  // Cleanup all test artifacts
  await prisma.procedureImport.deleteMany({ where: { sourceName: { contains: UNIQUE } } }).catch(() => {});
  await prisma.rawMaterial.deleteMany({ where: { sku: { startsWith: `E2E-` } } }).catch(() => {});
  await prisma.rawMaterial.deleteMany({ where: { sku: { startsWith: `PI-${UNIQUE}` } } }).catch(() => {});
  await prisma.purchaseOrder.deleteMany({ where: { notes: 'Auto-generated by stock replenishment pipeline' } }).catch(() => {});
  await srv.close();
});

test('E2E: analyze a procedure', async () => {
  const res = await api(srv.base, '/api/procedure-imports/analyze', {
    method: 'POST', headers: auth(),
    body: JSON.stringify({ text: PROCEDURE, sourceName: `e2e-${UNIQUE}.txt` }),
  });
  assert.equal(res.status, 201, JSON.stringify(res.body).slice(0, 300));
  assert.equal(res.body.import.status, 'pending');
  assert.ok(res.body.import.materialPlan.length >= 1);
});

test('E2E: approve creates materials + recipe + product + procedure', async () => {
  const created = await api(srv.base, '/api/procedure-imports/analyze', {
    method: 'POST', headers: auth(),
    body: JSON.stringify({ text: PROCEDURE, sourceName: `e2e-approve-${UNIQUE}.txt` }),
  });
  assert.equal(created.status, 201);
  const id = created.body.import.id;

  const approved = await api(srv.base, `/api/procedure-imports/${id}/approve`, {
    method: 'POST', headers: auth(), body: JSON.stringify({}),
  });
  assert.equal(approved.status, 200, JSON.stringify(approved.body).slice(0, 300));
  assert.equal(approved.body.import.status, 'approved');
  const result = approved.body.result;
  assert.ok(result.productId && result.recipeId, JSON.stringify(result));

  // Verify product is linked to procedure
  const product = await prisma.product.findUnique({ where: { id: result.productId } });
  assert.equal(product.procedureDocumentId, result.procedureDocumentId);

  // Verify recipe has lines
  const recipe = await prisma.bOMRecipe.findUnique({ where: { id: result.recipeId }, include: { lines: true } });
  assert.ok(recipe.lines.length >= 1);

  // Verify procedure document
  const doc = await prisma.procedureDocument.findUnique({ where: { id: result.procedureDocumentId } });
  assert.equal(doc.status, 'draft');

  // Cleanup
  await prisma.bOMLine.deleteMany({ where: { recipeId: result.recipeId } }).catch(() => {});
  await prisma.bOMRecipe.delete({ where: { id: result.recipeId } }).catch(() => {});
  await prisma.procedureDocument.delete({ where: { id: result.procedureDocumentId } }).catch(() => {});
  await prisma.product.delete({ where: { id: result.productId } }).catch(() => {});
  await prisma.rawMaterial.deleteMany({ where: { id: { in: result.createdMaterialIds || [] } } }).catch(() => {});
});

test('E2E: QC endpoint accepts passed/failed', async () => {
  const orders = await prisma.order.findMany({ take: 1 });
  if (!orders.length) return;
  const pass = await api(srv.base, `/api/orders/${orders[0].id}/qc`, {
    method: 'PATCH', headers: auth(),
    body: JSON.stringify({ qcStatus: 'passed', qcNotes: 'E2E test' }),
  });
  assert.equal(pass.status, 200);
  assert.equal(pass.body.qcStatus, 'passed');

  const fail = await api(srv.base, `/api/orders/${orders[0].id}/qc`, {
    method: 'PATCH', headers: auth(),
    body: JSON.stringify({ qcStatus: 'failed', qcNotes: 'E2E fail test' }),
  });
  assert.equal(fail.status, 200);
  assert.equal(fail.body.qcStatus, 'failed');

  // Reset
  await api(srv.base, `/api/orders/${orders[0].id}/qc`, {
    method: 'PATCH', headers: auth(),
    body: JSON.stringify({ qcStatus: null }),
  });
});

